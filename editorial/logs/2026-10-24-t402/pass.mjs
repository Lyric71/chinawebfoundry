import fs from 'node:fs';
const [stage, step, ...words] = process.argv.slice(2);
const log = 'editorial/logs/2026-10-24.md';
const draft = 'editorial/output/china-latency-vantage-point-study.md';
const dir = 'editorial/logs/2026-10-24-t402';
const version = `${dir}/${stage}-v${String(step).padStart(2, '0')}.md`;
if (fs.existsSync(version)) throw new Error('Version already exists');
fs.copyFileSync(draft, version);
let s = fs.readFileSync(log, 'utf8');
const heading = stage === 'ca' ? '## Createarticle tracker' : '## Content-quality-us tracker';
const start = s.indexOf(heading);
const end = s.indexOf('\n## ', start + heading.length);
const section = s.slice(start, end < 0 ? s.length : end);
const revised = section.replace(new RegExp(`\\[ \\] ${step} `), `[x] ${step} `);
if (section === revised) throw new Error('Tracker step not found');
s = s.slice(0, start) + revised + (end < 0 ? '' : s.slice(end));
s += `\n### ${stage} ${step}: completed\n\n${words.join(' ')}\n\nArtifact: ${version}\n`;
fs.writeFileSync(log, s);
console.log(`${stage} ${step} complete: ${words.join(' ')}; artifact ${version}`);
